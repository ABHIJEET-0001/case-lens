"""
app/db/models.py
────────────────
SQLAlchemy ORM models for CaseLens.

Tables:
  users          — platform users (Clerk / Researcher / Judge)
  judgments      — ingested Indian court judgments
  summaries      — cached abstractive summaries (one per judgment)
  pending_cases  — cases awaiting resolution, with prediction data
"""
import uuid
from datetime import datetime, date

from sqlalchemy import (
    Column, String, Text, Integer, Float, Date, DateTime,
    ForeignKey, Enum as SAEnum, Boolean, func,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship, DeclarativeBase
import enum


class Base(DeclarativeBase):
    pass


# ── Enums ─────────────────────────────────────────────────────────────────────

class UserRole(str, enum.Enum):
    clerk = "clerk"
    researcher = "researcher"
    judge = "judge"


class CaseStatus(str, enum.Enum):
    pending = "pending"
    hearing = "hearing"
    reserved = "reserved"         # judgment reserved
    disposed = "disposed"


class ComplexityClass(str, enum.Enum):
    low = "Low"
    medium = "Medium"
    high = "High"
    Low = "Low"
    Medium = "Medium"
    High = "High"


# ── Users ─────────────────────────────────────────────────────────────────────

class User(Base):
    __tablename__ = "users"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    email = Column(String(255), nullable=False, unique=True, index=True)
    hashed_password = Column(String(255), nullable=False)
    full_name = Column(String(255), nullable=True)
    role = Column(SAEnum(UserRole), nullable=False, default=UserRole.clerk)
    is_active = Column(Boolean, nullable=False, default=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    # Backref: cases assigned to this user
    assigned_cases = relationship("PendingCase", back_populates="assigned_user")


# ── Judgments ─────────────────────────────────────────────────────────────────

class Judgment(Base):
    """
    One row = one court judgment ingested from a dataset or scraper.
    full_text stores the raw cleaned text; embeddings live in FAISS (by id).
    """
    __tablename__ = "judgments"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    title = Column(String(512), nullable=False)
    citation = Column(String(255), nullable=True, index=True)   # e.g. "AIR 2019 SC 1234"
    court = Column(String(255), nullable=False, index=True)
    case_type = Column(String(100), nullable=True, index=True)  # CRL, CIV, WP, etc.
    bench = Column(String(512), nullable=True)                  # judge names
    judgment_date = Column(Date, nullable=True, index=True)
    outcome = Column(String(100), nullable=True)                # allowed / dismissed / etc.
    source_url = Column(Text, nullable=True)
    full_text = Column(Text, nullable=False)
    word_count = Column(Integer, nullable=True)
    is_indexed = Column(Boolean, nullable=False, default=False)  # True after FAISS embed
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    summary = relationship("Summary", back_populates="judgment", uselist=False)


# ── Summaries ─────────────────────────────────────────────────────────────────

class Summary(Base):
    """
    Cached abstractive summary for a judgment.
    Generated by Gemini API; fallback to extractive (TextRank) when unavailable.
    """
    __tablename__ = "summaries"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    judgment_id = Column(
        UUID(as_uuid=True),
        ForeignKey("judgments.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )
    facts = Column(Text, nullable=True)
    issue = Column(Text, nullable=True)
    holding = Column(Text, nullable=True)
    outcome_text = Column(Text, nullable=True)
    model_used = Column(String(100), nullable=True)   # e.g. "gemini-1.5-flash" or "textrank"
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    judgment = relationship("Judgment", back_populates="summary")


# ── Pending Cases ─────────────────────────────────────────────────────────────

class PendingCase(Base):
    """
    A live case awaiting resolution — the core unit of the prediction pipeline.
    Precedent-strength features and prediction outputs are stored here after
    the prediction API is called.
    """
    __tablename__ = "pending_cases"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

    # ── Case identity ──────────────────────────────────────────────────────────
    case_no = Column(String(100), nullable=False, unique=True, index=True)
    case_type = Column(String(100), nullable=False)              # CRL.A, WP, CIV, etc.
    court = Column(String(255), nullable=False)
    filing_date = Column(Date, nullable=False)
    hearings_count = Column(Integer, nullable=False, default=0)
    description = Column(Text, nullable=True)
    status = Column(SAEnum(CaseStatus), nullable=False, default=CaseStatus.pending)
    assigned_to = Column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=True)

    # ── Precedent-strength features (computed by retrieval module) ─────────────
    top1_similarity = Column(Float, nullable=True)
    mean_top5_similarity = Column(Float, nullable=True)
    count_above_threshold = Column(Integer, nullable=True)   # count sim > 0.65
    similarity_spread = Column(Float, nullable=True)         # std dev of top-5
    precedent_age_mean = Column(Float, nullable=True)        # avg age in days
    outcome_agreement = Column(Float, nullable=True)         # fraction same outcome

    # ── Prediction outputs ─────────────────────────────────────────────────────
    predicted_days = Column(Float, nullable=True)
    complexity = Column(SAEnum(ComplexityClass, values_callable=lambda x: [e.value for e in x]), nullable=True)
    priority_score = Column(Float, nullable=True)            # higher = more urgent
    shap_reasons = Column(Text, nullable=True)               # JSON string of top factors
    prediction_updated_at = Column(DateTime(timezone=True), nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())

    assigned_user = relationship("User", back_populates="assigned_cases")
